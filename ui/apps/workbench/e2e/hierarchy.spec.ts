import { expect, test } from '@playwright/test';

test('extract, reuse, edit and trace a shared schematic block without 3D', async ({ page }) => {
  const errors: string[] = [];
  const renderers: string[] = [];
  page.on('request',(r)=>{if(r.url().includes('Bench3D-'))renderers.push(r.url());});
  page.on('pageerror', (e) => errors.push(e.message));
  await page.goto('/?mock=1');
  await page.getByRole('button', { name: 'Sheets and reusable blocks', exact: true }).click();
  const active = page.getByLabel('Active sheet', { exact: true });
  await page.getByRole('button', { name: /^R1, / }).press('Enter');
  await page.getByLabel('Block identifier', { exact: true }).fill('pullup');
  await page.getByRole('button', { name: 'Extract selection', exact: true }).click();
  await expect(active).toHaveValue('@pullup');
  await expect(page.getByRole('button', { name: 'Sheet port BTN, R1.2', exact: true })).toBeVisible();
  await active.selectOption('');
  await page.getByRole('button', { name: 'Place', exact: true }).click();
  await expect(active.locator('option[value="X2"]')).toHaveCount(1);
  await active.selectOption('X1');
  await page.getByRole('button', { name: /^R1, / }).press('Enter');
  const value = page.getByLabel('Parameter R1.resistance', { exact: true });
  await value.fill('2200');
  await value.press('Tab');
  await expect(value).toBeEnabled();
  await active.selectOption('X2');
  await page.getByRole('button', { name: /^R1, / }).press('Enter');
  await expect(page.getByLabel('Parameter R1.resistance', { exact: true })).toHaveValue('2200');
  await page.getByRole('button', { name: 'Undo sheet edit', exact: true }).click();
  await expect(page.getByLabel('Parameter R1.resistance', { exact: true })).toHaveValue('10k');
  await active.selectOption('X1');
  await page.getByLabel('Trace local net', { exact: true }).selectOption('BTN');
  const trace = page.getByRole('region', { name: 'Cross-sheet trace', exact: true });
  await expect(trace).toContainText('Main · BTN');
  await expect(trace).toContainText('X1 · BTN');
  await expect(trace).not.toContainText('X2 · BTN');
  expect(errors).toEqual([]);
  expect(renderers).toEqual([]);
});

test('author parameters, copy across sheets, edit buses and locate project checks', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.goto('/?mock=1');
  await page.getByRole('button', { name: 'Sheets and reusable blocks', exact: true }).click();
  await page.getByRole('button', { name: /^R1, / }).press('Enter');
  await page.getByLabel('Block identifier', { exact: true }).fill('stage');
  await page.getByRole('button', { name: 'Extract selection', exact: true }).click();
  const active = page.getByLabel('Active sheet', { exact: true });
  await expect(active).toHaveValue('@stage');
  await page.getByRole('button', { name: 'New parameter', exact: true }).click();
  await page.getByLabel('Declaration name', { exact: true }).fill('resistance');
  await page.getByLabel('Declaration default', { exact: true }).fill('2k');
  await page.getByRole('button', { name: 'Add declaration', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Edit resistance', exact: true })).toBeVisible();
  await page.getByRole('button', { name: /^R1, / }).press('Enter');
  const value = page.getByLabel('Parameter R1.resistance', { exact: true });
  await value.fill('$resistance'); await value.press('Tab');
  await expect(value).toBeEnabled();
  await page.getByRole('button', { name: 'Edit resistance', exact: true }).click();
  await page.getByLabel('Declaration name', { exact: true }).fill('upper');
  await page.getByRole('button', { name: 'Save declaration', exact: true }).click();
  await expect(page.getByLabel('Parameter R1.resistance', { exact: true })).toHaveValue('$upper');
  await page.getByRole('button', { name: 'Remove port BTN', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Port BTN is in use' })).toBeVisible();
  await page.getByLabel('Bus name', { exact: true }).fill('RAILS');
  await page.getByLabel('Bus member nets', { exact: true }).fill('3V3, BTN');
  await page.getByRole('button', { name: 'Add bus', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Trace bus RAILS bit 0, 3V3', exact: true })).toBeVisible();
  await active.selectOption('');
  await page.getByRole('button', { name: /^X1, / }).press('Space');
  await page.getByRole('button', { name: 'Copy sheet selection', exact: true }).click();
  await page.getByRole('button', { name: 'Paste into sheet', exact: true }).click();
  await expect(active.locator('option[value="X2"]')).toHaveCount(1);
  await page.getByLabel('Find in project', { exact: true }).fill('R1 resistor');
  const results = page.getByRole('region', { name: 'Project search results', exact: true });
  await results.getByRole('button').filter({ hasText: 'X2 · R1' }).click();
  await expect(active).toHaveValue('X2');
  await page.getByRole('button', { name: /^Project checks/ }).click();
  await expect(page.getByRole('region', { name: 'Project electrical and drawing review', exact: true })).toBeVisible();
  await page.getByLabel('Check source', { exact: true }).selectOption('coverage');
  await expect(page.getByRole('list', { name: 'Project check results', exact: true })).toContainText('No checks match this filter.');
  await page.getByLabel('Check source', { exact: true }).selectOption('drawing');
  await expect(page.getByRole('list', { name: 'Project check results', exact: true })).toContainText('drawing');
  expect(errors).toEqual([]);
});

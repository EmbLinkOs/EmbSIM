"""Peripheral coverage per MCU (07 M6: "a coverage table per board").

For every MCU in the catalog: each peripheral of its register description,
the model its mcu.json binds to it, and whether the engine has that model
(core/mcu/models.c's table). A peripheral is

  modelled    its model exists in the engine;
  registers   bound to "storage" (its registers hold values, nothing more);
  missing     bound to a model the engine does not have yet, or to none:
              its registers hold values and an access raises
              mcu.unsupported_access.

The boards built on the MCU and its fidelity's omissions are listed with it.
A model that exists may still decline a unit (the FE310's QSPI0) or leave out
behaviour; the omissions say so.

    coverage.py              write docs/coverage.md
    coverage.py --check      fail if docs/coverage.md is not current
"""
import argparse
import fnmatch
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "coverage.md"


def engine_models() -> set:
    text = (ROOT / "core" / "mcu" / "models.c").read_text(encoding="utf-8")
    return set(re.findall(r'\{\s*"([a-z0-9_-]+)",\s*&', text))


def boards_by_mcu() -> dict:
    out: dict = {}
    for f in sorted((ROOT / "catalog" / "boards").glob("*/board.json")):
        d = json.loads(f.read_text(encoding="utf-8"))
        mcu = d.get("mcu")
        mid = mcu.get("ref") if isinstance(mcu, dict) else mcu
        if mid:
            out.setdefault(mid, []).append(d.get("name", d.get("id")))
    return out


def binding(peripheral: str, rules: list):
    for r in rules:
        if fnmatch.fnmatchcase(peripheral, r["match"]):
            return r["model"]
    return None


def table(mcu_file: Path, models: set, boards: dict) -> tuple:
    mcu = json.loads(mcu_file.read_text(encoding="utf-8"))
    regs = json.loads((mcu_file.parent / mcu["register_file"]["file"]).read_text(encoding="utf-8"))
    rules = mcu.get("peripherals", [])
    rows, counts = [], {"modelled": 0, "registers": 0, "missing": 0}
    for p in regs["peripherals"]:
        model = binding(p["name"], rules)
        if model == "storage":
            state = "registers"
        elif model and model in models:
            state = "modelled"
        else:
            state = "missing"
        counts[state] += 1
        rows.append((p["name"], model or "—", state))
    lines = [f"## {mcu['name']} (`{mcu['id']}`)", ""]
    on = boards.get(mcu["id"], [])
    lines.append(f"Boards: {', '.join(on) if on else 'none in the catalog'}.  ")
    total = sum(counts.values())
    lines.append(f"{counts['modelled']} of {total} peripherals modelled, {counts['registers']} registers only, "
                 f"{counts['missing']} missing.")
    lines += ["", "| Peripheral | Model | State |", "|---|---|---|"]
    mark = {"modelled": "modelled", "registers": "registers only", "missing": "**missing**"}
    lines += [f"| {n} | `{m}` | {mark[s]} |" if m != "—" else f"| {n} | — | {mark[s]} |" for n, m, s in rows]
    omissions = mcu.get("fidelity", {}).get("functional", {}).get("omissions", [])
    if omissions:
        lines += ["", "Declared omissions: " + "; ".join(omissions) + "."]
    return mcu["name"], counts, "\n".join(lines)


def render() -> str:
    models = engine_models()
    boards = boards_by_mcu()
    sections, summary = [], []
    for f in sorted((ROOT / "catalog" / "mcus").glob("*/*/mcu.json")):
        name, counts, text = table(f, models, boards)
        sections.append(text)
        total = sum(counts.values())
        summary.append(f"| {name} | {counts['modelled']} | {counts['registers']} | {counts['missing']} | {total} |")
    head = [
        "# Peripheral coverage",
        "",
        "Generated by `tools/catalog/coverage.py` from the catalog's MCU descriptions and the",
        "engine's model table; CI fails when it is not current. A peripheral marked",
        "**missing** keeps its register values and raises `mcu.unsupported_access`; one",
        "marked modelled may still leave out behaviour its MCU's fidelity declares. The",
        "evidence for each model is in [STATUS.md](STATUS.md).",
        "",
        "| MCU | Modelled | Registers only | Missing | Peripherals |",
        "|---|---|---|---|---|",
        *summary,
        "",
    ]
    return "\n".join(head) + "\n" + "\n\n".join(sections) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if docs/coverage.md is not current")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print("docs/coverage.md is not current: run tools/catalog/coverage.py")
            return 1
        print("docs/coverage.md is current")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""Writes main.c: one test function per ARMv7E-M DSP instruction (and the
ARMv7-M ones they sit beside), each over 4096 operand pairs, hashed.

    gen.py    regenerate main.c beside this file"""
from pathlib import Path

TWO = ["sadd8", "sadd16", "sasx", "ssax", "ssub8", "ssub16", "qadd8", "qadd16", "qasx", "qsax", "qsub8", "qsub16",
       "shadd8", "shadd16", "shasx", "shsax", "shsub8", "shsub16", "uadd8", "uadd16", "uasx", "usax", "usub8", "usub16",
       "uqadd8", "uqadd16", "uqasx", "uqsax", "uqsub8", "uqsub16", "uhadd8", "uhadd16", "uhasx", "uhsax", "uhsub8",
       "uhsub16", "sel", "sxtab16", "uxtab16", "smuad", "smuadx", "smusd", "smusdx", "usad8", "qadd", "qsub", "qdadd",
       "qdsub", "smulbb", "smulbt", "smultb", "smultt", "smulwb", "smulwt", "smmul", "smmulr", "pkhbt", "pkhtb",
       "uxtab", "sxtab", "uxtah", "sxtah"]
THREE = ["smlad", "smladx", "smlsd", "smlsdx", "usada8", "smlabb", "smlabt", "smlatb", "smlatt", "smlawb", "smlawt",
         "smmla", "smmlar", "smmls", "smmlsr"]
ONE = [("sxtb16", "sxtb16 %0, %1"), ("uxtb16", "uxtb16 %0, %1"), ("sxtb16_ror8", "sxtb16 %0, %1, ror #8"),
       ("uxtb16_ror16", "uxtb16 %0, %1, ror #16"), ("ssat16_1", "ssat16 %0, #1, %1"),
       ("ssat16_8", "ssat16 %0, #8, %1"), ("ssat16_16", "ssat16 %0, #16, %1"), ("usat16_0", "usat16 %0, #0, %1"),
       ("usat16_7", "usat16 %0, #7, %1"), ("usat16_15", "usat16 %0, #15, %1"), ("ssat_5", "ssat %0, #5, %1"),
       ("usat_9_asr", "usat %0, #9, %1, asr #3"), ("rbit", "rbit %0, %1"), ("rev16", "rev16 %0, %1"),
       ("revsh", "revsh %0, %1")]
LONG = ["smlald", "smlaldx", "smlsld", "smlsldx", "smlalbb", "smlalbt", "smlaltb", "smlaltt", "umaal"]

HEAD = '''/* SPDX-License-Identifier: Apache-2.0 */
/* Copyright 2026 Junior Deogracias */
/* main.c -- ARMv7E-M's DSP instructions over 4096 operand pairs each, the
 * results and APSR's GE and Q flags folded into one FNV-1a hash per
 * instruction, printed through semihosting. The same image runs on QEMU's
 * mps2-an386 (Cortex-M4) and on EmbSIM's nRF52840 (Cortex-M4F); their
 * outputs must agree (expected.txt is QEMU's; tests/protocol/test_dsp.py).
 * Generated by gen.py. */
#include <stdint.h>

#define N 4096

static uint32_t seed = 0x12345678u;
static uint32_t rnd(void)
{
    /* xorshift32, with the edge values mixed in */
    static const uint32_t edge[] = { 0, 1, 0x7f, 0x80, 0xff, 0x7fff, 0x8000, 0xffff, 0x7fffffffu,
                                     0x80000000u, 0xffffffffu, 0x7f7f7f7fu, 0x80808080u, 0x00ff00ffu };
    seed ^= seed << 13;
    seed ^= seed >> 17;
    seed ^= seed << 5;
    if ((seed & 7) == 0)
        return edge[(seed >> 3) % (sizeof edge / sizeof edge[0])];
    return seed;
}

static uint32_t hash;
static void mix(uint32_t v)
{
    int i;
    for (i = 0; i < 4; i++) {
        hash ^= (v >> (8 * i)) & 0xff;
        hash *= 16777619u;
    }
}

static uint32_t flags(void)
{
    uint32_t a;
    __asm__ volatile("mrs %0, apsr" : "=r"(a));
    return a & 0x080f0000u; /* Q and GE */
}

static void clear_flags(void)
{
    uint32_t z = 0;
    __asm__ volatile("msr apsr_nzcvqg, %0" : : "r"(z));
}

static void semi_write0(const char *s)
{
    register uint32_t r0 __asm__("r0") = 4; /* SYS_WRITE0 */
    register const char *r1 __asm__("r1") = s;
    __asm__ volatile("bkpt 0xab" : "+r"(r0) : "r"(r1) : "memory");
}

static void report(const char *name)
{
    static const char hex[] = "0123456789abcdef";
    char line[48];
    int i = 0, k;
    while (*name && i < 32)
        line[i++] = *name++;
    line[i++] = ' ';
    for (k = 7; k >= 0; k--)
        line[i++] = hex[(hash >> (4 * k)) & 15];
    line[i++] = '\\n';
    line[i] = 0;
    semi_write0(line);
}
'''

TAIL = '''static void semi_exit(void)
{
    register uint32_t r0 __asm__("r0") = 0x18; /* SYS_EXIT */
    register uint32_t r1 __asm__("r1") = 0x20026; /* ADP_Stopped_ApplicationExit */
    __asm__ volatile("bkpt 0xab" : : "r"(r0), "r"(r1));
}

int main(void)
{
%s    semi_write0("done\\n");
    semi_exit();
    for (;;)
        ;
}
'''


def body(name: str, decl: str, asm: str, mixes: str, pre: str = "") -> str:
    return f'''static void t_{name}(void)
{{
    int i;
    hash = 2166136261u;
    for (i = 0; i < N; i++) {{
        {decl}
        clear_flags();
        {pre}__asm__ volatile({asm});
{mixes}        mix(flags());
    }}
    report("{name}");
}}
'''


def main() -> None:
    out = [HEAD]
    for n in TWO:
        pre = '__asm__ volatile("uadd8 %0, %1, %2" : "=r"(r) : "r"(b), "r"(a));\n        ' if n == "sel" else ""
        out.append(body(n, "uint32_t a = rnd(), b = rnd(), r;", f'"{n} %0, %1, %2" : "=r"(r) : "r"(a), "r"(b)',
                        "        mix(r);\n", pre))
    for n in THREE:
        out.append(body(n, "uint32_t a = rnd(), b = rnd(), c = rnd(), r;",
                        f'"{n} %0, %1, %2, %3" : "=r"(r) : "r"(a), "r"(b), "r"(c)', "        mix(r);\n"))
    for n, ins in ONE:
        out.append(body(n, "uint32_t a = rnd(), r;", f'"{ins}" : "=r"(r) : "r"(a)', "        mix(r);\n"))
    for n in LONG:
        out.append(body(n, "uint32_t a = rnd(), b = rnd(), lo = rnd(), hi = rnd();",
                        f'"{n} %0, %1, %2, %3" : "+r"(lo), "+r"(hi) : "r"(a), "r"(b)',
                        "        mix(lo);\n        mix(hi);\n"))
    names = TWO + THREE + [n for n, _ in ONE] + LONG
    out.append(TAIL % "".join(f"    t_{n}();\n" for n in names))
    (Path(__file__).resolve().parent / "main.c").write_text("".join(out))


if __name__ == "__main__":
    main()

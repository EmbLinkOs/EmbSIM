/* the text DYNAMIC and the archive's notes.txt hold */
static size_t make_text(char *out, size_t cap)
{
    size_t n = 0;
    int i;
    for (i = 0; i < 400; i++) {
        char rep[64];
        int k, r = i % 7;
        rep[0] = 0;
        for (k = 0; k < r; k++)
            memcpy(rep + 8 * k, "abcdefgh", 9);
        n += (size_t)snprintf(out + n, cap - n, "line %d: %s %d\n", i, rep, (i * 7919) % 10007);
    }
    return n;
}

static char text[20000];
static size_t text_len;

static void test_streams(void)
{
    uint8_t out[20000];
    size_t got = 0;
    CHECK(esk_inflate(STORED, sizeof STORED, out, sizeof out, &got) == ES_OK);
    CHECK(got == 12 && memcmp(out, "stored bytes", 12) == 0);
    CHECK(esk_inflate(FIXED, sizeof FIXED, out, sizeof out, &got) == ES_OK);
    CHECK(got == 26 && memcmp(out, "hello hello hello, embsim!", 26) == 0);
    CHECK(esk_inflate(DYNAMIC, sizeof DYNAMIC, out, sizeof out, &got) == ES_OK);
    CHECK_EQ(got, text_len);
    CHECK(got == text_len && memcmp(out, text, text_len) == 0);
    /* an output one byte too small is refused, not overrun */
    CHECK(esk_inflate(DYNAMIC, sizeof DYNAMIC, out, text_len - 1, &got) == ES_EINVAL);
    CHECK_EQ(esk_crc32((const uint8_t *)"123456789", 9), 0xcbf43926u);
}

/* every prefix and every one-byte change: refused, or decoded in bounds */
static void mangle(const uint8_t *in, size_t len)
{
    static uint8_t buf[4096], out[20000];
    size_t i, got;
    int ok = 0, refused = 0;
    if (len > sizeof buf)
        return;
    for (i = 0; i < len; i++) {
        es_status st = esk_inflate(in, i, out, sizeof out, &got);
        ok += st == ES_OK;
        refused += st != ES_OK;
    }
    for (i = 0; i < len; i++) {
        es_status st;
        memcpy(buf, in, len);
        buf[i] ^= (uint8_t)(0x5a + i);
        st = esk_inflate(buf, len, out, sizeof out, &got);
        ok += st == ES_OK;
        refused += st != ES_OK;
        CHECK(st != ES_OK || got <= sizeof out);
    }
    CHECK(refused > 0);
    CHECK(ok + refused == (int)(2 * len));
}

static void test_mangled(void)
{
    mangle(STORED, sizeof STORED);
    mangle(FIXED, sizeof FIXED);
    mangle(DYNAMIC, sizeof DYNAMIC);
}

static void test_archive(void)
{
    esk_alloc a;
    esk_zip z;
    char why[160];
    uint8_t *body = NULL, copy[sizeof ARCHIVE];
    size_t len = 0, i, n = 0;
    esk_alloc_init(&a, NULL);
    CHECK(esk_zip_open(&z, &a, ARCHIVE, sizeof ARCHIVE, why, sizeof why) == ES_OK);
    CHECK_EQ(z.n, 3);
    CHECK_STR(z.e[0].name, "lib/");
    CHECK(z.e[0].dir);
    CHECK_STR(z.e[1].name, "lib/library.json");
    CHECK_EQ(z.e[1].method, 0);
    CHECK_EQ(z.e[2].method, 8);
    CHECK(esk_zip_read(&z, 1, &body, &len, why, sizeof why) == ES_OK);
    CHECK(len == 13 && memcmp(body, "{\"name\": \"x\"}", 13) == 0);
    esk_free(&a, body, len + 1);
    CHECK(esk_zip_read(&z, 2, &body, &len, why, sizeof why) == ES_OK);
    CHECK(len == text_len && memcmp(body, text, text_len) == 0);
    esk_free(&a, body, len + 1);
    esk_zip_close(&z);
    /* every one-byte change: opened and read, or refused, never out of
     * bounds; a change in an entry's data is caught by its CRC */
    for (i = 0; i < sizeof ARCHIVE; i++) {
        size_t k;
        memcpy(copy, ARCHIVE, sizeof copy);
        copy[i] ^= 0xa5;
        if (esk_zip_open(&z, &a, copy, sizeof copy, why, sizeof why) != ES_OK)
            continue;
        for (k = 0; k < z.n; k++)
            if (esk_zip_read(&z, k, &body, &len, why, sizeof why) == ES_OK) {
                CHECK(len < sizeof copy * 64);
                esk_free(&a, body, len + 1);
            } else {
                n++;
            }
        esk_zip_close(&z);
    }
    CHECK(n > 0);
    /* not an archive; truncated */
    CHECK(esk_zip_open(&z, &a, (const uint8_t *)"PK\3\4 not really", 15, why, sizeof why) == ES_EINVAL);
    CHECK(esk_zip_open(&z, &a, ARCHIVE, sizeof ARCHIVE - 1, why, sizeof why) == ES_EINVAL);
    CHECK_EQ(a.live_bytes, 0);
}


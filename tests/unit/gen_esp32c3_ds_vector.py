"""Write tests/unit/esp32c3_ds_vector.h: one ESP32-C3 digital signature case
(RSA-1024) built as ESP-IDF's components/esp_security/test_apps/crypto_drivers/
main/gen_digital_signature_tests.py builds them, with Python's cryptography and
pow() as the independent reference. The RSA key comes from the OS's random
source, so each run writes a different case; the committed header is one."""
import hashlib
import hmac
import random
import struct
from pathlib import Path

from cryptography.hazmat.primitives.asymmetric import rsa
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

MAX_BITS = 3072  # the C3's maximum: Y, M and Rb each take 384 bytes in P


def le(number, bits):
    return number.to_bytes(bits // 8, 'little')


def main():
    rng = random.Random(1792324800)
    hmac_key = bytes(range(32))
    aes_key = hmac.new(hmac_key, b'\xff' * 32, hashlib.sha256).digest()
    iv = bytes(rng.randrange(256) for _ in range(16))
    key = rsa.generate_private_key(public_exponent=65537, key_size=1024)
    y, m = key.private_numbers().d, key.public_key().public_numbers().n
    rb = (1 << (1024 * 2)) % m
    mprime = (-pow(m, -1, 1 << 32)) & 0xFFFFFFFF
    length = 1024 // 32 - 1
    md = hashlib.sha256(le(y, MAX_BITS) + le(m, MAX_BITS) + le(rb, MAX_BITS) +
                        struct.pack('<II', mprime, length) + iv).digest()
    p = le(y, MAX_BITS) + le(m, MAX_BITS) + le(rb, MAX_BITS) + md + struct.pack('<II', mprime, length) + b'\x08' * 8
    enc = Cipher(algorithms.AES(aes_key), modes.CBC(iv)).encryptor()
    c = enc.update(p) + enc.finalize()
    x = rng.randrange(1, m)
    z = pow(x, y, m)

    def arr(name, data):
        rows = ['    ' + ', '.join('0x%02x' % b for b in data[i:i + 12]) + ',' for i in range(0, len(data), 12)]
        return 'static const u8 %s[%d] = {\n%s\n};\n' % (name, len(data), '\n'.join(rows))

    out = ['/* SPDX-License-Identifier: Apache-2.0 */', '/* Copyright 2026 Junior Deogracias */',
           '/* Generated by gen_esp32c3_ds_vector.py: an RSA-1024 digital signature case in',
           ' * the layout of ESP-IDF\'s gen_digital_signature_tests.py; the HMAC key is bytes',
           ' * 0..31 and Z = pow(X, Y, M) by Python. */', '']
    out.append(arr('ds_c', c))
    out.append(arr('ds_iv', iv))
    out.append(arr('ds_x', le(x, 1024)))
    out.append(arr('ds_z', le(z, 1024)))
    Path(__file__).with_name('esp32c3_ds_vector.h').write_text('\n'.join(out), encoding='utf-8')


if __name__ == '__main__':
    main()
